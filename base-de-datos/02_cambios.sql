BEGIN;

-- 1. En musuario agregar curp (18 caracteres, única) y foto_url
ALTER TABLE musuario 
  ADD COLUMN IF NOT EXISTS curp varchar(18) UNIQUE,
  ADD COLUMN IF NOT EXISTS foto_url varchar(255);

-- 2. Crear las tablas cpregunta, copcion y erespuesta
CREATE TABLE IF NOT EXISTS cpregunta (
  id_pregunta        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tipo_evaluacion integer      NOT NULL,
  id_oficio          integer,
  tema               varchar(150) NOT NULL,
  texto              text         NOT NULL,
  CONSTRAINT fk_pregunta_tipo   FOREIGN KEY (id_tipo_evaluacion) REFERENCES ctipo_evaluacion (id_tipo_evaluacion),
  CONSTRAINT fk_pregunta_oficio FOREIGN KEY (id_oficio)          REFERENCES coficio (id_oficio)
);

CREATE TABLE IF NOT EXISTS copcion (
  id_opcion   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pregunta integer      NOT NULL,
  texto       text         NOT NULL,
  puntos      integer      NOT NULL DEFAULT 0,
  CONSTRAINT fk_opcion_pregunta FOREIGN KEY (id_pregunta) REFERENCES cpregunta (id_pregunta) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS erespuesta (
  id_respuesta  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion integer      NOT NULL,
  id_pregunta   integer      NOT NULL,
  id_opcion     integer      NOT NULL,
  puntos        integer      NOT NULL DEFAULT 0,
  CONSTRAINT fk_resp_evaluacion FOREIGN KEY (id_evaluacion) REFERENCES eevaluacion (id_evaluacion),
  CONSTRAINT fk_resp_pregunta   FOREIGN KEY (id_pregunta)   REFERENCES cpregunta (id_pregunta),
  CONSTRAINT fk_resp_opcion     FOREIGN KEY (id_opcion)     REFERENCES copcion (id_opcion)
);

-- 3. En eevaluacion agregar en_curso (verdadero o falso) y caso_actual (número, empieza en 1)
ALTER TABLE eevaluacion 
  ADD COLUMN IF NOT EXISTS en_curso boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS caso_actual integer DEFAULT 1;

-- 4. En ctutorial agregar id_tipo_evaluacion, id_oficio y tema, y que id_evaluacion pueda ser vacío
ALTER TABLE ctutorial 
  ADD COLUMN IF NOT EXISTS id_tipo_evaluacion integer,
  ADD COLUMN IF NOT EXISTS id_oficio          integer,
  ADD COLUMN IF NOT EXISTS tema               varchar(150),
  ALTER COLUMN id_evaluacion DROP NOT NULL;

-- Asegurar las llaves foráneas de ctutorial si no estaban creadas
DO $$ 
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_tutorial_tipo') THEN
    ALTER TABLE ctutorial ADD CONSTRAINT fk_tutorial_tipo FOREIGN KEY (id_tipo_evaluacion) REFERENCES ctipo_evaluacion (id_tipo_evaluacion);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_tutorial_oficio') THEN
    ALTER TABLE ctutorial ADD CONSTRAINT fk_tutorial_oficio FOREIGN KEY (id_oficio) REFERENCES coficio (id_oficio);
  END IF;
END $$;

-- 5. En mpre_constancia agregar id_usuario y codigo (texto único)
ALTER TABLE mpre_constancia 
  ADD COLUMN IF NOT EXISTS id_usuario integer,
  ADD COLUMN IF NOT EXISTS codigo     varchar(50) UNIQUE;

DO $$ 
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_constancia_usuario') THEN
    ALTER TABLE mpre_constancia ADD CONSTRAINT fk_constancia_usuario FOREIGN KEY (id_usuario) REFERENCES musuario (id_usuario);
  END IF;
END $$;

COMMIT;