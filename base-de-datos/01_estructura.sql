BEGIN;

-- Limpieza (orden inverso por las llaves foráneas)
DROP TABLE IF EXISTS ctutorial        CASCADE;
DROP TABLE IF EXISTS mpre_constancia  CASCADE;
DROP TABLE IF EXISTS eevaluacion      CASCADE;
DROP TABLE IF EXISTS musuario         CASCADE;
DROP TABLE IF EXISTS ctipo_usuario    CASCADE;
DROP TABLE IF EXISTS ctipo_evaluacion CASCADE;
DROP TABLE IF EXISTS coficio          CASCADE;
DROP TABLE IF EXISTS calcaldia        CASCADE;

-- ---------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------
CREATE TABLE calcaldia (
  id_alcaldia     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_alcaldia varchar(100) NOT NULL
);

CREATE TABLE coficio (
  id_oficio     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_oficio varchar(100) NOT NULL
);

CREATE TABLE ctipo_evaluacion (
  id_tipo_evaluacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             varchar(100) NOT NULL
);

CREATE TABLE ctipo_usuario (
  id_tipo_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo            varchar(50) NOT NULL
);

-- ---------------------------------------------------------------------
-- Usuarios
-- NOTA: la columna "contraseña" se renombró a "contrasena" (sin ñ)
--       para evitar problemas con PostgREST / clientes de Supabase.
-- ---------------------------------------------------------------------
CREATE TABLE musuario (
  id_usuario      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_tipo_usuario integer      NOT NULL,
  id_alcaldia     integer      NOT NULL,
  id_oficio       integer      NOT NULL,
  nombre          varchar(150) NOT NULL,
  correo          varchar(150) NOT NULL,
  contrasena      varchar(255) NOT NULL,
  telefono        varchar(20)  NOT NULL,
  estatus         varchar(50)  NOT NULL DEFAULT 'En Diagnóstico',
  fecha_registro  timestamptz  DEFAULT now(),
  CONSTRAINT correo_unique   UNIQUE (correo),
  CONSTRAINT telefono_unique UNIQUE (telefono),
  CONSTRAINT fk_usuario_tipousu  FOREIGN KEY (id_tipo_usuario) REFERENCES ctipo_usuario (id_tipo_usuario),
  CONSTRAINT fk_usuario_alcaldia FOREIGN KEY (id_alcaldia)     REFERENCES calcaldia (id_alcaldia),
  CONSTRAINT fk_usuario_oficio   FOREIGN KEY (id_oficio)       REFERENCES coficio (id_oficio)
);

CREATE INDEX idx_usuario_tipousu  ON musuario (id_tipo_usuario);
CREATE INDEX idx_usuario_alcaldia ON musuario (id_alcaldia);
CREATE INDEX idx_usuario_oficio   ON musuario (id_oficio);

-- ---------------------------------------------------------------------
-- Evaluaciones
-- ---------------------------------------------------------------------
CREATE TABLE eevaluacion (
  id_evaluacion        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario           integer      NOT NULL,
  tipo_evaluacion      integer      NOT NULL,
  calificacion         numeric(5,2) DEFAULT 0.00,
  estado_aprobacion    varchar(50)  DEFAULT 'Pendiente',
  intentos_acumulados  integer      DEFAULT 0,
  fecha_ultimo_intento timestamptz,
  CONSTRAINT fk_evaluacion_usuario FOREIGN KEY (id_usuario)      REFERENCES musuario (id_usuario),
  CONSTRAINT fk_evaluacion_tipo    FOREIGN KEY (tipo_evaluacion) REFERENCES ctipo_evaluacion (id_tipo_evaluacion)
);

CREATE INDEX idx_evaluacion_usuario ON eevaluacion (id_usuario);
CREATE INDEX idx_evaluacion_tipo    ON eevaluacion (tipo_evaluacion);

-- ---------------------------------------------------------------------
-- Tutoriales (depende de eevaluacion)
-- ---------------------------------------------------------------------
CREATE TABLE ctutorial (
  id_tutorial          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion        integer      NOT NULL,
  titulo               varchar(150) NOT NULL,
  contenido_multimedia text         NOT NULL,
  CONSTRAINT fk_tutorial_evaluacion FOREIGN KEY (id_evaluacion) REFERENCES eevaluacion (id_evaluacion)
);

CREATE INDEX idx_tutorial_evaluacion ON ctutorial (id_evaluacion);

-- ---------------------------------------------------------------------
-- Pre-constancias (relación 1 a 1 con evaluación)
-- ---------------------------------------------------------------------
CREATE TABLE mpre_constancia (
  id_constancia     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evaluacion     integer      NOT NULL,
  folio_unico       varchar(50)  NOT NULL,
  fecha_emision     date         NOT NULL,
  fecha_vencimiento date         NOT NULL,
  firma_digital     text         NOT NULL,
  url_archivo_pdf   varchar(255) NOT NULL,
  CONSTRAINT constancia_evaluacion_unique UNIQUE (id_evaluacion),
  CONSTRAINT constancia_folio_unique      UNIQUE (folio_unico),
  CONSTRAINT fk_constancia_evaluacion FOREIGN KEY (id_evaluacion) REFERENCES eevaluacion (id_evaluacion)
);

