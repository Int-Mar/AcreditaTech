-- Opción única: 3 opciones (0 Alto, 5 Medio, 10 Bajo)
CREATE FUNCTION pg_temp.p_unica(ofi int, tm text, tx text,
  a text, b text, c text, ra text, rm text) RETURNS void
LANGUAGE plpgsql AS $f$
DECLARE pid int;
BEGIN
  INSERT INTO cpregunta (id_tipo_evaluacion, id_oficio, tema, texto, tipo_pregunta)
  VALUES (2, ofi, tm, tx, 'unica') RETURNING id_pregunta INTO pid;
  INSERT INTO copcion (id_pregunta, texto, puntos, nivel_riesgo, recomendacion) VALUES
    (pid, a, 0,  'Alto',  ra),
    (pid, b, 5,  'Medio', rm),
    (pid, c, 10, 'Bajo',  NULL);
END $f$;

-- Escala Likert: Nunca ... Siempre (inv = true cuando la escala va invertida)
CREATE FUNCTION pg_temp.p_likert(ofi int, tm text, tx text,
  inv boolean, ra text, rm text) RETURNS void
LANGUAGE plpgsql AS $f$
DECLARE pid int;
BEGIN
  INSERT INTO cpregunta (id_tipo_evaluacion, id_oficio, tema, texto, tipo_pregunta)
  VALUES (2, ofi, tm, tx, 'likert') RETURNING id_pregunta INTO pid;
  IF inv THEN
    INSERT INTO copcion (id_pregunta, texto, puntos, nivel_riesgo, recomendacion) VALUES
      (pid, 'Nunca',       10, 'Bajo',  NULL),
      (pid, 'Casi nunca',   8, 'Bajo',  NULL),
      (pid, 'A veces',      5, 'Medio', rm),
      (pid, 'Casi siempre', 2, 'Alto',  ra),
      (pid, 'Siempre',      0, 'Alto',  ra);
  ELSE
    INSERT INTO copcion (id_pregunta, texto, puntos, nivel_riesgo, recomendacion) VALUES
      (pid, 'Nunca',        0, 'Alto',  ra),
      (pid, 'Casi nunca',   2, 'Alto',  ra),
      (pid, 'A veces',      5, 'Medio', rm),
      (pid, 'Casi siempre', 8, 'Bajo',  NULL),
      (pid, 'Siempre',     10, 'Bajo',  NULL);
  END IF;
END $f$;

