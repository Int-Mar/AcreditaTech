-- Columna para bloquear usuarios
ALTER TABLE musuario
  ADD COLUMN IF NOT EXISTS bloqueado boolean NOT NULL DEFAULT false;

-- Ficha de salud ocupacional (una por usuario)
CREATE TABLE IF NOT EXISTS mficha_salud (
  id_ficha            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario          integer NOT NULL UNIQUE,
  dolor_espalda       varchar(20),
  dolor_hombros_cuello varchar(20),
  horas_trabajo_dia   integer,
  usa_casco           boolean,
  usa_guantes         boolean,
  usa_lentes          boolean,
  usa_calzado_seguridad boolean,
  observaciones       varchar(255),
  fecha_actualizacion timestamptz DEFAULT now(),
  CONSTRAINT fk_ficha_usuario FOREIGN KEY (id_usuario) REFERENCES musuario (id_usuario)
);

ALTER TABLE mficha_salud ENABLE ROW LEVEL SECURITY;